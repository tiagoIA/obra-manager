import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,getDoc,setDoc,updateDoc,getDocs,collection} from 'firebase/firestore';
import registration from './functions/company-registration.cjs';
import invitations from './functions/company-invitations.cjs';
const require = createRequire(new URL('./functions/package.json',import.meta.url));
const {initializeApp,deleteApp} = require('firebase-admin/app');
const {getFirestore,FieldValue} = require('firebase-admin/firestore');
const {createHash} = require('node:crypto');
const projectId = 'demo-obra-company-pilot';
const env = await initializeTestEnvironment({projectId,firestore:{host:'127.0.0.1',port:8180,rules:fs.readFileSync('firestore.rules','utf8')}});
const app = initializeApp({projectId},'invitation-test');
const db = getFirestore(app);
const timestamp = () => FieldValue.serverTimestamp();
const identity = (uid,email=uid+'@example.invalid',verified=true) => ({uid,token:{email,email_verified:verified}});
const cfcOwner = identity('cfc-owner'), pnvOwner = identity('pnv-owner');
let checks = 0;
const reject = async (promise,code) => {await assert.rejects(promise,error => error.code === code);checks++;};
const create = (auth,email,extra={}) => invitations.createCompanyInvite({db,auth,data:{email,...extra},timestamp});
const accept = (auth,token,extra={}) => invitations.acceptCompanyInvite({db,auth,data:{token,name:'Invited Test User',...extra},timestamp});
const revoke = (auth,token) => invitations.revokeCompanyInvite({db,auth,data:{token},timestamp});
try {
  await env.clearFirestore();
  const cfc = await registration.registerCompany({db,auth:cfcOwner,data:{name:'CFC Electric',ownerName:'CFC Test Admin'},timestamp});
  const pnv = await registration.registerCompany({db,auth:pnvOwner,data:{name:'PNV Electric',ownerName:'PNV Test Admin'},timestamp});
  await reject(create(null,'member@example.invalid'),'unauthenticated');
  await reject(create(identity('cfc-owner','cfc-owner@example.invalid',false),'member@example.invalid'),'failed-precondition');
  await reject(create(identity('outsider'),'member@example.invalid'),'permission-denied');
  await reject(create(cfcOwner,'member@example.invalid',{role:'owner'}),'invalid-argument');
  await reject(create(cfcOwner,'member@example.invalid',{companyId:pnv.companyId}),'invalid-argument');
  const invite = await create(cfcOwner,'  Member@Example.Invalid  ');
  assert.equal(invite.email,'member@example.invalid');checks++;
  assert.equal(invite.companyName,'CFC Electric');checks++;
  const hash = createHash('sha256').update(invite.token).digest('hex');
  const saved = await db.doc('companyInvites/'+hash).get();
  assert.equal(saved.exists,true);checks++;
  assert.equal(saved.data().token,undefined);checks++;
  const member = identity('member');
  await reject(accept(member,'invalid'),'invalid-argument');
  await reject(accept(identity('wrong-person'),invite.token),'permission-denied');
  await reject(accept(identity('member','member@example.invalid',false),invite.token),'failed-precondition');
  await reject(accept(member,invite.token,{role:'owner'}),'invalid-argument');
  const [accepted,retried] = await Promise.all([accept(member,invite.token),accept(member,invite.token)]);
  assert.equal(accepted.companyId,cfc.companyId);checks++;
  assert.equal(retried.companyId,cfc.companyId);checks++;
  assert.equal([accepted,retried].filter(item=>item.accepted).length,1);checks++;
  assert.equal((await db.doc(`companies/${cfc.companyId}/members/member`).get()).data().role,'employee');checks++;
  const memberDb = env.authenticatedContext('member').firestore();
  await assertSucceeds(getDoc(doc(memberDb,'companies',cfc.companyId)));checks++;
  await assertFails(getDoc(doc(memberDb,'companies',pnv.companyId)));checks++;
  await assertFails(updateDoc(doc(memberDb,'companies',cfc.companyId,'members','member'),{role:'owner'}));checks++;
  await assertFails(getDocs(collection(memberDb,'companyInvites')));checks++;
  await assertFails(getDoc(doc(memberDb,'companyInvites',hash)));checks++;
  await assertFails(setDoc(doc(memberDb,'companyInvites',hash),{role:'owner'}));checks++;
  await reject(create(member,'new-member@example.invalid'),'permission-denied');
  await reject(revoke(pnvOwner,invite.token),'permission-denied');
  await reject(revoke(cfcOwner,invite.token),'failed-precondition');
  const cross = await create(pnvOwner,'member@example.invalid');
  await reject(accept(member,cross.token),'failed-precondition');
  const revoked = await create(cfcOwner,'revoked@example.invalid');
  await revoke(cfcOwner,revoked.token);checks++;
  await reject(accept(identity('revoked'),revoked.token),'failed-precondition');
  const expired = await invitations.createCompanyInvite({db,auth:cfcOwner,data:{email:'expired@example.invalid'},timestamp,now:()=>0});
  await reject(accept(identity('expired'),expired.token),'deadline-exceeded');
  const supervisor = await create(pnvOwner,'supervisor@example.invalid',{role:'supervisor'});
  await accept(identity('supervisor'),supervisor.token);checks++;
  assert.equal((await db.doc(`companies/${pnv.companyId}/members/supervisor`).get()).data().role,'supervisor');checks++;
  const stale = await create(cfcOwner,'stale@example.invalid');
  await db.doc(`companies/${cfc.companyId}/members/${cfcOwner.uid}`).delete();
  await reject(accept(identity('stale'),stale.token),'failed-precondition');
  console.log(`PASS ${checks} invitation checks: CFC/PNV isolation, owner-only invitations, verified email binding, hashed tokens, atomic/idempotent acceptance, role protection, expiration, revocation and removed-inviter denial. Emulator only.`);
} finally {await env.cleanup();await db.terminate();await deleteApp(app);}
