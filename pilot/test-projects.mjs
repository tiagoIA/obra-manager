import fs from 'node:fs';
import assert from 'node:assert/strict';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,getDoc,getDocs,collection,setDoc,updateDoc,deleteDoc} from 'firebase/firestore';
import {createRequire} from 'node:module';
const require=createRequire(new URL('./functions/package.json',import.meta.url));
const {initializeApp,deleteApp}=require('firebase-admin/app');
const {getFirestore,FieldValue}=require('firebase-admin/firestore');
const {registerCompany}=require('./company-registration.cjs');
const {saveCompanyProject}=require('./company-projects.cjs');
const projectId='demo-obra-company-pilot';
const env=await initializeTestEnvironment({projectId,firestore:{host:'127.0.0.1',port:8180,rules:fs.readFileSync('firestore.rules','utf8')}});
const app=initializeApp({projectId},'project-tests'),db=getFirestore(app);
const auth=uid=>({uid,token:{email_verified:true,email:uid+'@example.invalid'}});
const timestamp=()=>FieldValue.serverTimestamp();
const run=(uid,data)=>saveCompanyProject({db,auth:uid?auth(uid):null,data,timestamp});
let checks=0;const ok=(a,b)=>{assert.deepEqual(a,b);checks++;};
const reject=async(p,code)=>{await assert.rejects(p,e=>e.code===code);checks++;};
try{
 await env.clearFirestore();
 const a=await registerCompany({db,auth:auth('owner-a'),data:{name:'Company A',ownerName:'Owner A'},timestamp});
 const b=await registerCompany({db,auth:auth('owner-b'),data:{name:'Company B',ownerName:'Owner B'},timestamp});
 const input={projectId:'test-project-00001',revision:0,name:'First project',address:'Test address',notes:'Test notes',status:'active'};
 await reject(run(null,input),'unauthenticated');
 await reject(saveCompanyProject({db,auth:{uid:'owner-a',token:{email_verified:false}},data:input,timestamp}),'failed-precondition');
 await reject(run('stranger',input),'permission-denied');
 await reject(run('owner-a',{...input,companyId:b.companyId}),'invalid-argument');
 await reject(run('owner-a',{...input,projectId:'../other'}),'invalid-argument');
 await reject(run('owner-a',{...input,name:' '}),'invalid-argument');
 const [first,retry]=await Promise.all([run('owner-a',input),run('owner-a',input)]);ok(first,retry);ok(first.revision,1);
 const ca=env.authenticatedContext('owner-a').firestore(),cb=env.authenticatedContext('owner-b').firestore();
 const path=`companies/${a.companyId}/projects/${input.projectId}`;
 const own=await assertSucceeds(getDoc(doc(ca,path)));checks++;ok(own.data().companyId,a.companyId);
 await assertFails(getDoc(doc(cb,path)));checks++;
 await assertFails(getDocs(collection(cb,`companies/${a.companyId}/projects`)));checks++;
 ok((await getDocs(collection(cb,`companies/${b.companyId}/projects`))).size,0);
 await assertFails(getDocs(collection(env.unauthenticatedContext().firestore(),`companies/${a.companyId}/projects`)));checks++;
 for(const client of [ca,cb]){
  await assertFails(setDoc(doc(client,path),{...input,companyId:a.companyId}));checks++;
  await assertFails(updateDoc(doc(client,path),{name:'Tamper'}));checks++;
  await assertFails(deleteDoc(doc(client,path)));checks++;
 }
 await db.doc(`companies/${a.companyId}/members/supervisor`).set({role:'supervisor'});
 await db.doc('userCompanies/supervisor').set({companyId:a.companyId,role:'owner'});
 await reject(run('supervisor',input),'permission-denied');
 await db.doc('userCompanies/owner-a').update({role:'employee'});
 const updated=await run('owner-a',{...input,revision:1,name:'Renamed'});ok(updated.revision,2);
 await reject(run('owner-a',{...input,revision:1,name:'Stale update'}),'aborted');
 await reject(run('owner-b',{...input,revision:2,name:'Cross company'}),'aborted');
 ok((await db.doc(path).get()).data().name,'Renamed');
 const archived=await run('owner-a',{...input,revision:2,name:'Renamed',status:'archived'});ok(archived.revision,3);
 ok((await db.doc(path).get()).data().status,'archived');
 const ownB=await run('owner-b',{...input,name:'Independent B'});ok(ownB.revision,1);
 ok((await db.doc(path).get()).data().name,'Renamed');
 await db.doc(`companies/${a.companyId}/members/owner-a`).delete();
 await reject(run('owner-a',{...input,revision:3}),'permission-denied');
 await assertFails(getDoc(doc(ca,path)));checks++;
 console.log(`PASS ${checks} project checks: company-derived ownership, isolated reads/listing, no direct client writes, idempotency, revision conflicts, archive, membership revocation.`);
}finally{await env.cleanup();await db.terminate();await deleteApp(app);}
