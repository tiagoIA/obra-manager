import assert from 'node:assert/strict';
import {validateGuide, referencesForTask, updateGuide} from '../public/installation-reference-core.mjs';
const draft = validateGuide({title:'Switch installation', materialIds:['m1','m1'], sources:[]});
assert.deepEqual(draft.materialIds,['m1']);
assert.throws(()=>validateGuide({...draft,status:'Reviewed'}),/reviewer/);
assert.throws(()=>validateGuide({...draft,photos:[{url:'javascript:alert(1)'}]}),/HTTPS/);
assert.throws(()=>validateGuide({...draft,sources:[{url:'https://user:pass@example.com'}]}),/credentials/);
const reviewed = {...draft,id:'g1',status:'Reviewed',reviewedBy:'reviewer',reviewedAt:'2026-10-22',sources:[{kind:'Manufacturer',title:'Installation instructions',url:'https://example.com/manual',checkedAt:'2026-10-22'}]};
assert.equal(referencesForTask({name:'Install lights'},[reviewed]).length,0);
assert.equal(referencesForTask({materialId:'m1'},[reviewed]).length,1);
assert.equal(referencesForTask({materialId:'m2'},[reviewed]).length,0);
assert.equal(referencesForTask({referenceIds:['g1']},[reviewed]).length,1);
assert.equal(referencesForTask({referenceIds:['g1']},[{...reviewed,status:'Archived'}]).length,0);
assert.equal(referencesForTask({materialId:'m1'},[{...reviewed,status:'Draft'}]).length,0);
assert.equal(referencesForTask({referenceIds:['g1']},[{...reviewed,status:'Draft'}]).length,1);
const first = updateGuide(null,draft,'editor');
assert.equal(first.revision,1);
assert.throws(()=>updateGuide(first,{...draft,revision:0},'editor'),/changed/);
assert.throws(()=>updateGuide(first,{...draft,revision:1},''),/Sign in/);
const changed = updateGuide({...reviewed,revision:2},{...reviewed,revision:2,description:'New instructions'},'editor');
assert.equal(changed.status,'Draft');assert.equal(changed.reviewedBy,null);assert.equal(changed.revision,3);
const unchanged = updateGuide({...reviewed,revision:2},{...reviewed,revision:2},'editor');
assert.equal(unchanged.status,'Reviewed');
console.log('Installation-reference behavior checks passed');
